import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { createRequire } from 'node:module';
import { createConfigServer } from './server.mjs';
import { prepareRemoteCatalog } from '../scripts/prepare-remote-catalog.mjs';

const require = createRequire(import.meta.url);
const { chromium } = require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const dataDir = await fs.mkdtemp(path.join(os.tmpdir(), 'flow-config-catalog-'));
let server;
let browser;
try {
    const seedPath = path.join(dataDir, 'catalog-seed.json');
    const seed = prepareRemoteCatalog(JSON.parse(await fs.readFile(new URL('../shared/model-config.default.json', import.meta.url), 'utf8')));
    await fs.writeFile(seedPath, JSON.stringify(seed));
    server = await createConfigServer({ dataDir, seedPath, port: 0, adminPassword: 'catalog-smoke-local',
        logger: { log() {}, warn() {}, error() {} } });
    browser = await chromium.launch({ channel: 'chrome', headless: true });
    const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
    const errors = [];
    page.on('pageerror', error => errors.push(error.message));
    page.on('dialog', dialog => dialog.accept());
    await page.goto(`${server.url}/admin`);
    await page.getByPlaceholder('管理密码').fill('catalog-smoke-local');
    await page.getByRole('button', { name: '登录', exact: true }).click();
    await page.locator('#catalogPane').waitFor({ state: 'visible' });
    const spriteResponse = await page.request.get(`${server.url}/admin/assets/flow-icons.svg`);
    assert.equal(spriteResponse.status(), 200);
    assert.ok(spriteResponse.headers()['content-type'].includes('image/svg+xml'));
    assert.ok((await spriteResponse.text()).includes('id="icon-arrow-up"'));
    const snapshot = async () => JSON.parse(await page.locator('#configText').inputValue());
    const original = await snapshot();
    const screenshots = path.resolve('output/playwright');
    await fs.mkdir(screenshots, { recursive: true });
    const assertLayout = async () => {
        const dimensions = await page.evaluate(() => ({ scroll: globalThis.document.documentElement.scrollWidth,
            width: globalThis.innerWidth, editor: globalThis.document.getElementById('formPane').getBoundingClientRect().bottom,
            publish: globalThis.document.querySelector('.publish-bar').getBoundingClientRect().top }));
        assert.ok(dimensions.scroll <= dimensions.width, `Horizontal overflow: ${JSON.stringify(dimensions)}`);
        assert.ok(dimensions.publish >= dimensions.editor - 1);
    };
    await assertLayout();
    await page.screenshot({ path: path.join(screenshots, 'config-catalog-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    await assertLayout();
    await page.screenshot({ path: path.join(screenshots, 'config-catalog-mobile.png') });
    await page.locator('#addModelBtn').click();
    await page.locator('#catalogDialog').waitFor({ state: 'visible' });
    await assertLayout();
    assert.ok(await page.locator('#catalogDialog').evaluate(element => element.getBoundingClientRect().right <= globalThis.innerWidth));
    await page.locator('#catalogDialogCancel').click();
    await page.setViewportSize({ width: 1440, height: 1000 });
    await page.locator('#catalogMode').selectOption('remote');
    await page.locator('#clearCatalogBtn').click();
    await page.locator('#catalogDialogConfirm').click();
    assert.deepEqual((await snapshot()).models, []);
    assert.equal((await snapshot()).catalogMode, 'remote');
    await page.locator('#undoCatalogBtn').click();
    assert.deepEqual((await snapshot()).models, original.models);
    await page.locator('#redoCatalogBtn').click();
    assert.deepEqual((await snapshot()).models, []);
    await page.locator('#addModelBtn').click();
    await page.locator('#catalogDialogLabel').fill('测试视频渠道');
    await page.locator('#catalogDialogModel').fill('catalog.smoke+video');
    await page.locator('#catalogDialogHosts').fill('ART.EXAMPLE.COM\ncart.example.com');
    await page.locator('#catalogDialogConfirm').click();
    await page.locator('#catalogDialog').waitFor({ state: 'hidden' });
    assert.equal((await snapshot()).models.length, 1);
    assert.deepEqual((await snapshot()).models[0].catalog.hosts, ['art.example.com', 'cart.example.com']);
    await page.locator('#createGroupBtn').click();
    await page.locator('#catalogDialogLabel').fill('测试渠道组');
    await page.locator('#catalogDialogConfirm').click();
    await page.locator('#catalogGroups [data-catalog-group]').waitFor({ state: 'visible' });
    assert.ok((await page.locator('#catalogGroups').textContent()).includes('当前使用：测试视频渠道'));
    await page.locator('#renameGroupBtn').click();
    await page.locator('#catalogDialogLabel').fill('备用分组测试');
    await page.locator('#catalogDialogConfirm').click();
    await page.locator('#copyModelBtn').click();
    await page.locator('#catalogDialogModel').fill('catalog.smoke.second');
    await page.locator('#catalogDialogConfirm').click();
    await page.locator('#catalogDialog').waitFor({ state: 'hidden' });
    assert.equal((await snapshot()).models.length, 2);
    assert.equal((await snapshot()).models[1].presentation.routeGroupLabel, '备用分组测试');
    await page.locator('#moveModelUpBtn').click();
    assert.equal((await snapshot()).models[1].presentation.routeOrder, 0);
    await page.locator('#catalogVisible').uncheck();
    assert.equal((await snapshot()).models[1].presentation.visible, false);
    assert.equal((await snapshot()).models[1].catalog.enabled, true);
    await page.locator('#undoCatalogBtn').click();
    assert.equal((await snapshot()).models[1].presentation.visible, true);
    await page.locator('#catalogMoveGroup').selectOption('');
    assert.equal((await snapshot()).models[1].presentation.routeGroup, '');
    await page.getByRole('tab', { name: '表单', exact: true }).click();
    await page.locator('[data-field="label"]').fill('独立视频模型');
    await page.getByRole('tab', { name: 'JSON', exact: true }).click();
    assert.equal((await snapshot()).models[1].presentation.label, '独立视频模型');
    await page.getByRole('tab', { name: '操作模式', exact: true }).click();
    await page.locator('#validateBtn').click();
    await page.waitForFunction(() => globalThis.document.getElementById('editorState').textContent.includes('校验通过'));
    await page.locator('#saveBtn').click();
    await page.waitForURL('**/admin?flash=*');
    const published = await fetch(`${server.url}/config`).then(response => response.json());
    assert.equal(published.catalogMode, 'remote');
    assert.equal(published.models.length, 2);
    assert.equal(published.models[1].presentation.label, '独立视频模型');
    const stableText = server.store.current().text;
    const stableName = server.store.current().name;
    assert.equal((await fetch(`${server.url}/config/preview`)).status, 404);
    await page.getByRole('link', { name: '源码预览', exact: true }).click();
    await page.waitForURL('**/admin?channel=preview');
    await page.locator('#catalogPane').waitFor({ state: 'visible' });
    assert.equal(await page.locator('.channel-nav a[aria-current="page"]').textContent(), '源码预览');
    assert.equal(await page.locator('#configForm input[name="channel"]').inputValue(), 'preview');
    assert.deepEqual((await snapshot()).models, published.models);
    await page.locator('#clearCatalogBtn').click();
    await page.locator('#catalogDialogConfirm').click();
    await page.locator('#saveBtn').click();
    await page.waitForURL(url => url.pathname === '/admin' && url.searchParams.get('channel') === 'preview'
        && url.searchParams.has('flash'));
    const emptyPreview = server.store.current('preview').name;
    assert.deepEqual((await fetch(`${server.url}/config/preview`).then(response => response.json())).models, []);
    assert.equal(await fetch(`${server.url}/config`).then(response => response.text()), stableText);
    await page.locator('#addModelBtn').click();
    await page.locator('#catalogDialogLabel').fill('Seedance 2.5 源码预览');
    await page.locator('#catalogDialogModel').fill('preview.seedance-2.5');
    await page.locator('#catalogDialogHosts').fill('art.ravenhash.org\ncart.ravenhash.org');
    await page.locator('#catalogDialogConfirm').click();
    await page.locator('#catalogDialog').waitFor({ state: 'hidden' });
    await page.locator('#createGroupBtn').click();
    await page.locator('#catalogDialogLabel').fill('Seedance 2.5 推荐渠道');
    await page.locator('#catalogDialogConfirm').click();
    await page.locator('#saveBtn').click();
    await page.waitForURL(url => url.pathname === '/admin' && url.searchParams.get('channel') === 'preview'
        && url.searchParams.has('flash'));
    assert.equal(server.store.current('preview').config.models[0].catalog.model, 'preview.seedance-2.5');
    assert.equal(server.store.current().name, stableName);
    assert.equal(server.store.current().text, stableText);
    await page.locator('#resetBtn').click();
    await page.waitForURL('**/admin?channel=preview');
    await page.locator('#catalogPane').waitFor({ state: 'visible' });
    assert.equal((await snapshot()).models.length, 1);
    assert.equal(await page.locator('.channel-nav a[aria-current="page"]').textContent(), '源码预览');
    await assertLayout();
    await page.screenshot({ path: path.join(screenshots, 'config-preview-admin-desktop.png') });
    await page.locator(`a[href="/admin?channel=preview&version=${emptyPreview}"]`).click();
    await page.waitForURL(url => url.searchParams.get('channel') === 'preview' && url.searchParams.get('version') === emptyPreview);
    assert.deepEqual((await snapshot()).models, []);
    await page.locator(`form[action="/admin/apply"]:has(input[value="${emptyPreview}"]) button`).click();
    await page.waitForURL(url => url.pathname === '/admin' && url.searchParams.get('channel') === 'preview'
        && url.searchParams.has('flash'));
    assert.equal(server.store.current('preview').name, emptyPreview);
    assert.equal(server.store.current().text, stableText);
    assert.deepEqual(errors, []);
    console.log('PASS catalog operation: desktop/mobile, clear/undo/redo, add/copy, group/rename/move, visibility, form/JSON, validate/publish, isolated preview clear/add/reset/rollback.');
} finally {
    await browser?.close();
    await server?.close();
    await fs.rm(dataDir, { recursive: true, force: true });
}
