import assert from 'node:assert/strict';
import fs from 'node:fs';
import console from 'node:console';
import { createConfigStore } from '/srv/flow-config/lib/store.mjs';

const directory = '/var/lib/flow-config';
const target = `${directory}/admin-model-prices.json`;
const before = fs.readFileSync(target, 'utf8');
const prices = JSON.parse(before);
const cartBefore = globalThis.structuredClone(prices.sites.find(site => site.host === 'cart.ravenhash.org'));
const site = prices.sites.find(site => site.host === 'art.ravenhash.org');
const model = site.models.find(entry => entry.model === 'yh-video-v25-cheap');
assert.equal(model.currency, 'CNY');
assert.deepEqual(model.prices, [{ label: '720p', amount: 4, unit: 'request' }]);
assert.deepEqual(cartBefore.models.find(entry => entry.model === model.model).prices, model.prices);
model.prices[0].amount = 3;
site.checkedAt = prices.checkedAt = new Date().toISOString();
assert.deepEqual(prices.sites.find(entry => entry.host === cartBefore.host), cartBefore);
const store = createConfigStore({ dataDir: directory });
const current = store.current();
const config = globalThis.structuredClone(current.config);
const entry = config.models.find(value => value.id === 'ravenhash-video.yh25-cheap');
assert.ok(entry);
entry.notes = entry.notes.replace('；4元/次', '');
const backup = `${directory}/operations/yihong-cheap-art-price3-${Date.now()}`;
fs.mkdirSync(backup, { recursive: true, mode: 0o700 });
fs.writeFileSync(`${backup}/admin-model-prices.json`, before, { mode: 0o600 });
fs.writeFileSync(`${backup}/config.json`, current.text, { mode: 0o600 });
assert.equal(fs.readFileSync(target, 'utf8'), before, 'Prices changed concurrently');
assert.equal(store.current().name, current.name, 'Catalog changed concurrently');
fs.writeFileSync(`${target}.price3-next`, JSON.stringify(prices, null, 2)+'\n', { mode: 0o600 });
fs.renameSync(`${target}.price3-next`, target);
const saved = store.save(config, { actor: 'codex', channel: 'stable', note: 'Seedance 2.5 Cheap art CNY 3/request; cart remains CNY 4/request' });
assert.equal(store.current('preview').name, saved.name);
console.log(JSON.stringify({ revision: saved.revision, version: saved.name, art: 3, cart: 4, unit: 'request', backup }));
